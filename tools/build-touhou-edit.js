"use strict";

/**
 * Build a local NeonScore edit from the user-provided th06_05.mid.
 * This is a personal, local arrangement; the Touhou composition remains
 * © ZUN / Team Shanghai Alice and is not intended for redistribution.
 */

const fs = require("fs");
const path = require("path");

globalThis.NS = globalThis.NS || {};
const U = require("../js/util.js");
require("../js/theory.js");
require("../js/presets.js");
const M = require("../js/model.js");
const MIDI = require("../js/midi.js");
const TEXT = require("../js/textscore.js");

const root = path.resolve(__dirname, "..");
const sourcePath = path.join(root, "TouhouMid", "th06_05.mid");
const outDir = path.join(root, "scores", "Touhou");
fs.mkdirSync(outDir, { recursive: true });

function takeSection(track, startBeat, endBeat, transpose) {
  if (!track) return [];
  const notes = [];
  track.notes.forEach((note) => {
    if (note.start < startBeat - 0.001 || note.start >= endBeat - 0.001) return;
    const duration = Math.min(note.dur, endBeat - note.start);
    if (duration <= 0.03) return;
    notes.push(M.note(
      U.clamp(note.pitch + transpose, 0, 127),
      note.start - startBeat,
      duration,
      note.vel
    ));
  });
  return notes;
}

async function main() {
  const buffer = fs.readFileSync(sourcePath);
  const arrayBuffer = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
  const midi = MIDI.parse(arrayBuffer, { title: "th06_05", maxTracks: 20 });
  const byChannel = new Map(midi.tracks.map((track) => [track.sourceChannel, track]));
  const melodySource = byChannel.get(7);
  const bassSource = byChannel.get(1);
  const harmonySource = byChannel.get(2);
  if (!melodySource || !bassSource) throw new Error("th06_05: expected channels 7 and 1");

  const startBeat = 12; // bar 4, where the main melody enters
  const endBeat = startBeat + 16 * 4;

  const song = M.createSong({
    title: "TH06_05 おてんば恋娘 · NeonScore Edit",
    bpm: midi.bpm,
    meter: "4/4",
    bars: 16,
    root: 2,
    mode: "major",
    progressionPreset: "axis",
    styleId: "synthwave",
  });
  M.applyStyle(song, "synthwave");
  song.chords = [
    "Bm7", "Bm7", "Bm7", "Bm7",
    "G", "G", "G", "A",
    "Bm7", "Bm7", "Bm7", "Bm7",
    "G", "G", "G", "A",
  ];
  song.density = 72;
  song.arpPattern = "updown";
  song.drumStyle = "classic";
  song.swing = 0;
  song.fx = { reverb: 38, delay: 24, drive: 34, sidechain: 82, brightness: 64 };

  const lead = song.tracks.find((track) => track.role === "lead");
  lead.name = "主旋律";
  lead.instrument = "neonSaw";
  lead.volume = 0.9;
  lead.notes = takeSection(melodySource, startBeat, endBeat, -12);

  M.generateArrangement(song, { preserveLead: true, seed: 6505 });

  const bass = song.tracks.find((track) => track.role === "bass");
  bass.name = "原曲贝斯";
  bass.instrument = "analogBass";
  bass.volume = 0.8;
  bass.notes = takeSection(bassSource, startBeat, endBeat, 12);

  const harmony = M.createTrack("extra", song.tracks.length, "synthwave");
  harmony.name = "电钢和声";
  harmony.role = "extra";
  harmony.instrument = "electricPiano";
  harmony.color = "#ffb36b";
  harmony.volume = 0.58;
  harmony.notes = takeSection(harmonySource, startBeat, endBeat, 0);
  song.tracks.push(harmony);

  const normalized = M.normalizeSong(song);
  const project = {
    app: "NEONSCORE",
    schema: 1,
    savedAt: new Date().toISOString(),
    source: {
      file: "TouhouMid/th06_05.mid",
      title: "おてんば恋娘 / Beloved Tomboyish Girl",
      game: "東方紅魔郷 ～ the Embodiment of Scarlet Devil.",
      composer: "ZUN / Team Shanghai Alice",
      note: "Local personal edit. Original composition © ZUN / Team Shanghai Alice; not for redistribution.",
    },
    song: normalized,
  };

  fs.writeFileSync(path.join(outDir, "th06_05-neonscore.json"), `${JSON.stringify(project, null, 2)}\n`, "utf8");
  fs.writeFileSync(path.join(outDir, "th06_05-neonscore.nst"), TEXT.stringify(normalized), "utf8");
  const blob = MIDI.write(normalized);
  fs.writeFileSync(path.join(outDir, "th06_05-neonscore.mid"), Buffer.from(await blob.arrayBuffer()));

  const localLibrary = [{
    id: "touhou-th06-05",
    title: "TH06_05 おてんば恋娘",
    description: "基于你提供的 th06_05.mid 的本地 16 小节编辑：原曲主旋律/贝斯/电钢 + 新写的铺底、琶音与门限鼓组。",
    styleLabel: "TOUHOU EDIT",
    style: "synthwave",
    color: "#ff5f9e",
    badge: "LOCAL",
    license: "Touhou Project music © ZUN / Team Shanghai Alice. Local personal edit from user-provided MIDI; not for redistribution.",
    song: normalized,
  }];
  fs.writeFileSync(path.join(root, "scores", "local-library.js"), `/* Generated by tools/build-touhou-edit.js — local example. */\nwindow.NEON_LOCAL_LIBRARY = ${JSON.stringify(localLibrary, null, 2)};\n`, "utf8");

  console.log({
    title: normalized.title,
    bpm: normalized.bpm,
    bars: normalized.bars,
    duration: M.durationSeconds(normalized).toFixed(1),
    tracks: normalized.tracks.map((track) => ({ name: track.name, role: track.role, notes: track.notes.length })),
    notes: M.noteCount(normalized),
    chords: normalized.chords,
  });
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
